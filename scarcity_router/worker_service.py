"""First-class worker service lifecycle: the systemd USER unit manager (#138).

One paired Linux/WSL worker runs as a normal OS service through a
generated systemd **user** unit — no root, no system unit, no second
worker launcher. This module owns the whole lifecycle surface of
``scarcity-router-worker service install|status|restart|uninstall``:

- **install** renders the unit from the ACTUAL installed executable
  (the console script or packaged binary this command ran through) and
  the ACTUAL worker state directory, preserving the adapter selection
  (``--codex-source`` instances, loopback Ollama, ZCode sources, or the
  legacy single-Codex flags) as ``ExecStart`` arguments. Rendering
  follows systemd's own substitution rules: every literal ``%`` is
  doubled (specifier expansion applies to ``ExecStart`` AND
  ``ReadWritePaths``, regardless of quoting) and the ``ExecStart`` line
  suppresses ``$``-variable substitution with the documented ``:``
  executable prefix — every path stays the literal path it was rendered
  from. It operates on the already-paired identity and uses the STORED
  server origin — there is no ``--server`` here. The unit embeds no
  credential: pairing identity, provider-controlled homes and rotation
  state all live in the 0700 state directory the unit merely points at.
  A ZCode-source unit additionally excepts exactly the ZCode CLI's own
  resolved state home (``$HOME/.zcode``) from ``ProtectHome=read-only``
  — normal ZCode execution writes its session/runtime state there — so
  the write grant is worker state + that one directory + the authorized
  workspace, never a writable ``$HOME``.
- **Idempotent and honest.** The rendered unit is deterministic
  (byte-stable for identical inputs): re-running install with the same
  flags re-writes nothing and stays green. A DIFFERENT generated unit
  replaces the previous one (the documented configuration-update path,
  applied by ``service restart``). An existing unit that was NOT
  generated by us is never touched — install refuses with the removal
  recipe instead of silently clobbering an unrelated unit or a
  hand-edited copy of the retired ``examples/`` unit.
- **systemd owns the daemon.** No self-daemonizing logic: the unit runs
  the ordinary ``run`` command in the foreground under the user manager,
  ``Restart=on-failure`` covers process death (the runtime's own bounded
  reconnect backoff covers connection loss), SIGTERM reaches the
  runtime's deterministic stop path, and logs land in the journal.
  ``loginctl linger`` is handled deliberately and visibly: install
  reports the state and attempts to enable it for the invoking user,
  and a failure is a visible remediation-bearing warning — never a
  silent pass and never a hard failure of the install itself.
- **One worker per state directory, enforced.** The lifetime
  single-instance lock (:class:`scarcity_router.worker_local_store.WorkerStateDirLock`)
  makes a foreground worker and the service worker mutually exclusive;
  the second process fails closed with a useful message.

Security boundaries kept intact (D-044; the #138 comment on worker
transport): the worker origin is never an install input, so service
tooling can neither introduce a plaintext non-loopback origin nor weaken
verified-TLS ``srws://`` requirements — it reuses exactly the stored
origin ``run`` would use. No secret enters the unit file, the CLI
output, or any error message; ``systemctl``/``loginctl`` are the only
subprocesses, with no credential-bearing arguments.

Custom CA configuration is deliberately absent: child G (#139) persists
CA trust through the supported worker configuration; unit files never
carry ad-hoc ``SSL_CERT_FILE`` shell hacks.

Non-goals (issue #138): Windows service mechanics (the M10 tray remains
the Windows path), root/system units, our own daemonizing logic, and
configuration migration. One service unit per user account is the
supported shape; a second worker on one host is a second user account
with its own state directory and service.
"""

